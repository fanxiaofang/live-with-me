import { test, expect } from '@playwright/test';
import { DEFAULT_ROOM_LAYOUT } from '../../src/components/layout-gizmo/layoutStore';
import { stableScene } from './helpers';
import fs from 'node:fs';

for (const width of [1200, 390]) {
  test(`desk calibration draft, export and room preview preserve saved layout at ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 900 });
    const layout = structuredClone(DEFAULT_ROOM_LAYOUT);
    layout['desk-group'].screen.x += 3;
    layout['attic-chair'].screen.x += 1;
    await page.addInitScript(value => localStorage.setItem('live_with_me_room_layout_v6', JSON.stringify(value)), layout);
    await stableScene(page);
    const stored = await page.evaluate(() => localStorage.getItem('live_with_me_room_layout_v6'));
    const personIds = await page.locator('#panoramic-world-stage [data-person-id]').evaluateAll(nodes => nodes.map(n => n.getAttribute('data-person-id')));
    const originalLaptop = await page.locator('#desk-slot-laptop').getAttribute('transform');
    await page.getByRole('button', { name: '检视工位椅子 (空椅 / 组合态)', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '工位椅与桌前坐姿' });
    await dialog.getByRole('button', { name: '接触校准 · 草稿', exact: true }).click();
    const board = dialog.getByRole('region', { name: '桌椅接触校准工具' });
    await expect(board).toBeVisible();
    await expect(board.locator('[data-desk-study-frame]')).toHaveAttribute('data-desk-study-frame', 'straight');
    await expect(page.locator('#panoramic-world-stage [data-desk-study-frame]')).toHaveCount(0);
    const keyboardX = Number(await board.getByRole('spinbutton', { name: '键盘 X', exact: true }).inputValue());
    await board.getByRole('spinbutton', { name: '键盘 X', exact: true }).fill(String(keyboardX + 50));
    await expect(board.locator('[data-sofa-arms]').first()).toHaveAttribute('data-hand-mode', 'armrest');
    await board.getByRole('button', { name: '撤销一步', exact: true }).click();
    await expect(board.getByRole('spinbutton', { name: '键盘 X', exact: true })).toHaveValue(String(keyboardX));
    const anchor = board.locator('[data-calibration-anchor="desk-laptop"]');
    await anchor.scrollIntoViewIfNeeded();
    const position = await anchor.boundingBox();
    await page.mouse.move(position!.x + position!.width / 2, position!.y + position!.height / 2);
    await page.mouse.down(); await page.mouse.move(position!.x + 18, position!.y - 5, { steps: 3 }); await page.mouse.up();
    expect(Number(await board.getByRole('spinbutton', { name: '键盘 X', exact: true }).inputValue())).not.toBe(keyboardX);
    await board.getByRole('button', { name: '撤销一步', exact: true }).click();
    await expect(board.getByRole('spinbutton', { name: '键盘 X', exact: true })).toHaveValue(String(keyboardX));
    await board.getByRole('combobox', { name: '桌面轮廓', exact: true }).selectOption('cove');
    const height = board.getByRole('slider', { name: '桌面高度', exact: true });
    await height.focus(); await height.press('End');
    await expect(height).toHaveValue('27');
    const draftLaptop = await board.locator('[data-asset-id="desk-slot-laptop"]').getAttribute('transform');
    expect(draftLaptop).not.toBe(originalLaptop);
    await board.getByRole('button', { name: '对照原稿', exact: true }).click();
    await expect(board.locator('[data-asset-id="minimal-craft-desk-frame"]')).toHaveCount(1);
    await expect(board.locator('[data-desk-study-frame]')).toHaveCount(0);
    await board.getByRole('button', { name: '返回草稿', exact: true }).click();
    await expect(height).toHaveValue('27');
    const jsonDownload = page.waitForEvent('download');
    await board.getByRole('button', { name: '导出参数', exact: true }).click();
    const json = await jsonDownload;
    await json.saveAs(info.outputPath('desk-study.json'));
    const parameters = JSON.parse(fs.readFileSync(info.outputPath('desk-study.json'), 'utf8'));
    expect(parameters.status).toBe('draft-not-approved');
    expect(parameters.surface.height).toBe(27);
    expect(parameters.layout['desk-cup'].screen).toEqual(layout['desk-cup'].screen);
    const svgDownload = page.waitForEvent('download');
    await board.getByRole('button', { name: '导出当前 SVG', exact: true }).click();
    const svg = await svgDownload;
    await svg.saveAs(info.outputPath('desk-study.svg'));
    const exported = fs.readFileSync(info.outputPath('desk-study.svg'), 'utf8');
    const svgCheck = await page.evaluate(content => {
      const doc = new DOMParser().parseFromString(content, 'image/svg+xml');
      const ids = [...doc.querySelectorAll('[id]')].map(n => n.id);
      const broken = [...doc.querySelectorAll('*')].flatMap(n => [...n.attributes].flatMap(a => [...a.value.matchAll(/url\(#([^)]*)\)/g)].map(m => m[1]))).filter(id => !ids.includes(id));
      return { parseError: Boolean(doc.querySelector('parsererror')), broken, helpers: doc.querySelectorAll('[data-calibration-guides], [data-calibration-anchor]').length, duplicate: ids.length !== new Set(ids).size };
    }, exported);
    expect(svgCheck).toEqual({ parseError: false, broken: [], helpers: 0, duplicate: false });
    await board.getByRole('button', { name: '恢复初始草稿', exact: true }).click();
    await expect(height).toHaveValue('22.6');
    await board.getByRole('combobox', { name: '桌面轮廓', exact: true }).selectOption('cove');
    await dialog.evaluate(node => { node.scrollTop = 0; });
    expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath(`tool-final-${width}.png`) });
    const previewLaptop = await board.locator('[data-asset-id="desk-slot-laptop"]').getAttribute('transform');
    await board.getByRole('button', { name: '放回房间试看', exact: true }).click();
    await expect(dialog).not.toBeVisible();
    const bar = page.getByRole('complementary', { name: '桌面草稿场景试放', exact: true });
    await expect(bar).toBeVisible();
    await expect(page.getByRole('button', { name: '全屋 2.5D 布局校准器', exact: true })).toHaveCount(0);
    await expect(page.locator('#panoramic-world-stage [data-desk-study-frame]')).toHaveAttribute('data-desk-study-frame', 'cove');
    await expect(page.locator('#desk-slot-laptop')).toHaveAttribute('transform', previewLaptop!);
    expect(await page.locator('#panoramic-world-stage [data-person-id]').evaluateAll(nodes => nodes.map(n => n.getAttribute('data-person-id')))).toEqual(personIds);
    expect(await page.evaluate(() => localStorage.getItem('live_with_me_room_layout_v6'))).toBe(stored);
    await page.getByRole('button', { name: '收起面板（查看完整约克郡风光）', exact: true }).click();
    await page.screenshot({ path: info.outputPath(`room-final-${width}.png`) });
    await bar.getByRole('button', { name: '返回接触校准', exact: true }).click();
    await expect(board).toBeVisible();
    await expect(board.getByRole('combobox', { name: '桌面轮廓', exact: true })).toHaveValue('cove');
    await expect(board.getByRole('button', { name: '撤销一步', exact: true })).toBeEnabled();
    await board.getByRole('button', { name: '放回房间试看', exact: true }).click();
    await bar.getByRole('button', { name: '结束试放并恢复', exact: true }).click();
    await expect(page.locator('[data-desk-study-frame], [data-calibration-guides]')).toHaveCount(0);
    await expect(page.locator('#desk-slot-laptop')).toHaveAttribute('transform', originalLaptop!);
    expect(await page.evaluate(() => localStorage.getItem('live_with_me_room_layout_v6'))).toBe(stored);
    await page.getByTitle('展开同住人面板', { exact: true }).click();
    await page.getByRole('button', { name: '检视工位椅子 (空椅 / 组合态)', exact: true }).click();
    await expect(board).toBeVisible();
    await expect(board.getByRole('combobox', { name: '桌面轮廓', exact: true })).toHaveValue('straight');
    await dialog.getByRole('button', { name: '关闭工位椅查看', exact: true }).press('Escape');
    await expect(dialog).not.toBeVisible();
    await expect(page.locator('[data-calibration-guides], [data-desk-study-frame]')).toHaveCount(0);
    // A clean, real-scene study for review, with the contact overlay switched off.
    await page.getByRole('button', { name: '检视工位椅子 (空椅 / 组合态)', exact: true }).click();
    await board.getByRole('combobox', { name: '桌面轮廓', exact: true }).selectOption('cove');
    await board.getByRole('checkbox', { name: '显示接触点', exact: true }).uncheck();
    const sampleDownload = page.waitForEvent('download');
    await board.getByRole('button', { name: '导出参数', exact: true }).click();
    await (await sampleDownload).saveAs(info.outputPath(`sample-${width}.json`));
    await board.getByRole('button', { name: '放回房间试看', exact: true }).click();
    await page.getByRole('button', { name: '收起面板（查看完整约克郡风光）', exact: true }).click();
    await expect(page.locator('[data-calibration-guides]')).toHaveCount(0);
    await page.screenshot({ path: info.outputPath(`sample-room-${width}.png`) });
    await page.getByRole('button', { name: '整栋小屋', exact: true }).click();
    await page.screenshot({ path: info.outputPath(`sample-overview-${width}.png`) });
    await bar.getByRole('button', { name: '结束试放并恢复', exact: true }).click();
    expect(await page.evaluate(() => localStorage.getItem('live_with_me_room_layout_v6'))).toBe(stored);
  });
}
