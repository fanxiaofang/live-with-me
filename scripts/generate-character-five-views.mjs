import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';

const root='docs/architecture/metrics/CHARACTER-NW-SVG-2026-10-16/approved';
const approval=JSON.parse(fs.readFileSync(`${root}/user-approval.json`,'utf8'));
const scale=0.039734395750332004;
const origin={x:-553.5*scale,y:-47.86666666666667-110*scale};
const heads={}; let common;
const scope=(text,id)=>text.replaceAll(`nw-${id}`,'NW_PREFIX');
const colors={
  '#57483d':'var(--nw-hair)', '#b8afa0':'var(--nw-hair)', '#e4c983':'var(--nw-hair)',
  '#514435':'var(--nw-hair)', '#463c33':'var(--nw-hair-shade)',
  '#f6d3b8':'var(--nw-skin)', '#f5d4b9':'var(--nw-skin)', '#f7d6bd':'var(--nw-skin)',
  '#3a4b59':'var(--nw-hat-shade)', '#465e6f':'var(--nw-hat)', '#3c5262':'var(--nw-hat-shade)', '#435d70':'var(--nw-hat)',
  '#e1795c':'var(--nw-shirt-light)', '#df775b':'var(--nw-shirt)', '#e27b5e':'var(--nw-shirt-light)',
  '#986348':'var(--nw-shirt-shade)', '#ac5c45':'var(--nw-shirt-shade)', '#ad6247':'var(--nw-shirt-shade)',
};
const colorize=text=>Object.entries(colors).reduce((result,[hex,variable])=>result.replaceAll(hex,variable),text);
const labels={shorthair:'经典短发',curly:'层叠长卷发',sidepart:'偏分低束发',shaggy:'双色蓬松碎发'};
for(const asset of approval.files){
  const svg=fs.readFileSync(asset.snapshot,'utf8');
  assert.equal(crypto.createHash('sha256').update(svg).digest('hex'),asset.sha256);
  const start=svg.indexOf('<defs>'),headStart=svg.indexOf('<g data-part="head"');
  const shared=scope(svg.slice(start,headStart),asset.id);
  if(common===undefined)common=shared;else assert.equal(shared,common);
  const head=scope(svg.slice(headStart,svg.lastIndexOf('</svg>')).trim(),asset.id);
  const hat=head.match(/<g data-part="beanie"><path d="([^"]+)"/)[1];
  const withoutPom=`M547,133 C603,130 652,153 686.86,194.14${hat.slice(hat.indexOf('C687.8,198.92'),hat.indexOf('C578.74,131.94'))}C563,133 553,133 547,133Z`;
  heads[asset.id]={sourceSha256:asset.sha256,head:colorize(head),hatWithPom:hat,hatWithoutPom:withoutPom};
  const views=[['front','正面'],['left','左侧'],['back','背面'],['right','右侧'],['nw','NW 斜侧']];
  const panels=views.map(([direction,label],i)=>{
    const source=fs.readFileSync(`public/character-${asset.id}-standing-${direction}.svg`,'utf8');
    const inner=source.replace(/^<svg\b[^>]*>/,'').replace(/<\/svg>\s*$/,'');
    let content=direction==='nw'?`<g data-character-pose="standing" data-facing="NW-eight-view" transform="translate(${origin.x},${origin.y}) scale(${scale})">${inner}</g>`:inner;
    // Original standalone exports may reuse semantic IDs between directions.
    // Scope IDs only in the new combined sheet, preserving every source path.
    for(const id of new Set([...content.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]))){
      const local=`five-${asset.id}-${direction}-${id}`;
      content=content.replaceAll(`id="${id}"`,`id="${local}"`).replaceAll(`url(#${id})`,`url(#${local})`).replaceAll(`href="#${id}"`,`href="#${local}"`);
    }
    return `<g data-view="${direction}" transform="translate(${40+i*292},0)"><text x="132" y="140" text-anchor="middle" fill="#ded4c7" font-size="18">${label}</text><rect x="0" y="166" width="264" height="370" rx="10" fill="#ddd8cf"/><svg x="0" y="166" width="264" height="370" viewBox="-20 -50 40 56">${content}</svg></g>`;
  }).join('');
  fs.writeFileSync(`public/character-${asset.id}-standing-5views.svg`,`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1500 590" width="1500" height="590" role="img" aria-label="${labels[asset.id]}站姿五视图" style="font-family:'Microsoft YaHei',sans-serif"><rect width="1500" height="590" fill="#211e1b"/><text x="40" y="56" fill="#f5ede2" font-size="28">${labels[asset.id]} · 站姿五视图</text><text x="40" y="92" fill="#c7b7a4" font-size="15">正面、左侧、背面、右侧、NW 斜侧</text>${panels}</svg>\n`);
}
fs.writeFileSync('src/components/characters/finalizedNwStandingAssets.ts',`// Generated by scripts/generate-character-five-views.mjs from finalized SVGs.\nexport const FINALIZED_NW_STANDING = ${JSON.stringify({scale,origin,common:colorize(common),heads},null,2)} as const;\n`);
console.log('Generated four native five-view sheets and one shared NW standing asset.');
